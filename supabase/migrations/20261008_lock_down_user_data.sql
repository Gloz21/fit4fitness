-- Fit4Fitness: lock down user data
--
-- Before this script, the data tables had no access rules, so anyone with the app's
-- public (anon) key could read every user's rows. This script:
--   1. Backs up every data table into a private `backup_20261008` schema.
--   2. Normalizes usernames to lowercase (the app signs in with lowercase names) and
--      removes the older capitalized duplicates (kept in the backup).
--   3. Links every row to its owner's Supabase Auth account (`owner` column).
--   4. Turns on Row Level Security: signed-in users can only see and change their own rows.
--   5. Creates the missing `workout_sessions` and `exercises` tables with the same rules.
--   6. Adds `delete_my_account()` so Delete Account removes the login, not just the data.
--
-- Run it once in Supabase Dashboard -> SQL Editor. It runs as one transaction:
-- if any step fails, nothing is changed. Safe to re-run.

begin;

-- 1. Backups (private schema, not reachable through the app's API) --------------------
create schema if not exists backup_20261008;
revoke all on schema backup_20261008 from anon, authenticated;
create table if not exists backup_20261008.user_profiles as table public.user_profiles;
create table if not exists backup_20261008.workouts      as table public.workouts;
create table if not exists backup_20261008.nutrition     as table public.nutrition;
create table if not exists backup_20261008.saved_recipes as table public.saved_recipes;
-- Extra safety: even if this schema were ever exposed, RLS with no policies blocks all access
alter table backup_20261008.user_profiles enable row level security;
alter table backup_20261008.workouts      enable row level security;
alter table backup_20261008.nutrition     enable row level security;
alter table backup_20261008.saved_recipes enable row level security;

-- 2. Create the tables the app expects but that were never created ---------------------
create table if not exists public.workout_sessions (
  id bigint generated by default as identity primary key,
  user_id text not null unique,
  sessions jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.exercises (
  id bigint generated by default as identity primary key,
  user_id text not null unique,
  custom_exercises jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- RLS on from the start; the per-user policy is added in the loop below
alter table public.workout_sessions enable row level security;
alter table public.exercises        enable row level security;

-- 3-4. Per table: dedupe + lowercase usernames, link owners, replace all policies -------
do $$
declare
  t text;
  pol record;
begin
  foreach t in array array['user_profiles', 'workouts', 'nutrition', 'saved_recipes', 'workout_sessions', 'exercises'] loop
    -- Drop capitalized duplicates ("Averya" when "averya" exists, or the older of two)
    execute format($f$
      delete from public.%1$I p
      using public.%1$I q
      where lower(p.user_id) = lower(q.user_id)
        and p.id <> q.id
        and p.user_id <> lower(p.user_id)
        and (q.user_id = lower(q.user_id) or q.updated_at > p.updated_at)
    $f$, t);

    execute format('update public.%I set user_id = lower(user_id) where user_id <> lower(user_id)', t);

    -- Owner column: filled automatically for new rows; deleting an account deletes its rows
    execute format(
      'alter table public.%I add column if not exists owner uuid default auth.uid() references auth.users(id) on delete cascade',
      t
    );
    execute format('create index if not exists %I on public.%I (owner)', t || '_owner_idx', t);

    -- Existing rows: match "<username>@fit4fitness.app" accounts to user_id
    execute format($f$
      update public.%1$I d
      set owner = u.id
      from auth.users u
      where d.owner is null
        and lower(u.email) = d.user_id || '@fit4fitness.app'
    $f$, t);

    -- Remove every existing policy (including any "allow all") before adding ours
    for pol in select policyname from pg_policies where schemaname = 'public' and tablename = t loop
      execute format('drop policy %I on public.%I', pol.policyname, t);
    end loop;

    execute format('alter table public.%I enable row level security', t);

    -- Signed-in users can read/write only rows they own. New rows must use their own
    -- username, so nobody can create a row under someone else's name.
    execute format($f$
      create policy "Users can manage their own rows" on public.%I
        for all to authenticated
        using (owner = auth.uid())
        with check (
          owner = auth.uid()
          and user_id = lower(split_part(auth.jwt() ->> 'email', '@', 1))
        )
    $f$, t);
  end loop;
end $$;

-- 6. Real account deletion --------------------------------------------------------------
-- Deleting the auth user also deletes all their rows (owner ... on delete cascade).
create or replace function public.delete_my_account()
returns void
language plpgsql
security definer
set search_path = public, auth
as $$
declare
  uid uuid := auth.uid();
begin
  if uid is null then
    raise exception 'Not signed in';
  end if;
  delete from auth.users where id = uid;
end;
$$;

revoke all on function public.delete_my_account() from public, anon;
grant execute on function public.delete_my_account() to authenticated;

commit;

-- Report: rows per table and how many were linked to an account. "unlinked" rows had no
-- matching login (e.g. an account deleted earlier); they stay stored but nobody can see them.
select 'user_profiles' as table_name, count(*) as total_rows, count(owner) as linked, count(*) - count(owner) as unlinked from public.user_profiles
union all select 'workouts', count(*), count(owner), count(*) - count(owner) from public.workouts
union all select 'nutrition', count(*), count(owner), count(*) - count(owner) from public.nutrition
union all select 'saved_recipes', count(*), count(owner), count(*) - count(owner) from public.saved_recipes
union all select 'workout_sessions', count(*), count(owner), count(*) - count(owner) from public.workout_sessions
union all select 'exercises', count(*), count(owner), count(*) - count(owner) from public.exercises;
